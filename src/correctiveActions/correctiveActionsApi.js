// یک ستون در دیتابیس: یعنی مهلت گذشته ولی هنوز به‌طور رسمی بسته/منقضی
// اعلام نشده (برخلاف status="expired" که یک تصمیم صریح است)
export function isOverdue(action) {
  if (!action.dueDate) return false;
  if (action.status === "closed" || action.status === "expired") return false;
  return new Date(action.dueDate) < new Date(new Date().toDateString());
}

