// ---------- KPI ----------

export function computeKpis(actions) {
  const kpis = { total: actions.length, open: 0, in_progress: 0, done_pending_approval: 0, closed: 0, expired: 0, overdue: 0 };
  actions.forEach((a) => {
    if (kpis[a.status] !== undefined) kpis[a.status] += 1;
    if (isOverdue(a)) kpis.overdue += 1;
  });
  return kpis;
}
