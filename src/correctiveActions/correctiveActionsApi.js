export async function loadCorrectiveActions() {
  const companyId = getCurrentCompanyId();
  const filter = companyId ? `&company_id=eq.${companyId}` : "";
  const rows = await sb(`corrective_actions?select=*&order=created_at.desc${filter}`);
  return (sbOk(rows) ? rows : []).map(fromRow);
}

// جلوگیری از تکرار: آیا برای این ارزیابی از قبل یک اقدام اصلاحی صادر شده؟
export async function loadCorrectiveActionForAssessment(assessmentId) {
  if (!assessmentId) return null;
  const rows = await sb(`corrective_actions?linked_assessment_id=eq.${assessmentId}&select=*&order=created_at.desc&limit=1`);
  return sbOk(rows) && rows.length > 0 ? fromRow(rows[0]) : null;
}

// نسخه‌ی دسته‌ای — برای صفحه‌ی نتایج که همزمان چند ارزیابی را لیست می‌کند
// (جلوگیری از N+1 کوئری). خروجی: نگاشت assessmentId -> اقدام اصلاحی
export async function loadCorrectiveActionsForAssessments(assessmentIds) {
  if (!assessmentIds || assessmentIds.length === 0) return {};
  const idList = assessmentIds.map((id) => `"${id}"`).join(",");
  const rows = await sb(`corrective_actions?linked_assessment_id=in.(${idList})&select=*&order=created_at.desc`);
  const map = {};
  if (sbOk(rows)) {
    rows.forEach((r) => {
      // اولین (جدیدترین، چون قبلاً desc مرتب شده) برای هر ارزیابی کافی است
      if (!map[r.linked_assessment_id]) map[r.linked_assessment_id] = fromRow(r);
    });
  }
  return map;
}

export async function createCorrectiveAction(rec, createdBy, explicitCompanyId) {
  const companyId = explicitCompanyId || getCurrentCompanyId();
  // شماره‌ی خودکار: CA-<تعداد فعلی + 1> — برای شمارش دقیق‌تر، تعداد رکوردهای
  // همین شرکت را می‌خوانیم؛ اگر کاربر خودش شماره‌ای وارد کرده باشد، همان حفظ می‌شود.
  let actionNumber = rec.actionNumber?.trim();
  if (!actionNumber) {
    const countRows = await sb(`corrective_actions?select=id${companyId ? `&company_id=eq.${companyId}` : ""}`);
    const nextSeq = (sbOk(countRows) ? countRows.length : 0) + 1;
    actionNumber = `CA-${String(nextSeq).padStart(4, "0")}`;
  }
  const payload = { ...toDb({ ...rec, actionNumber }), company_id: companyId, created_by: createdBy || "" };
  const rows = await sb("corrective_actions", { method: "POST", body: JSON.stringify([payload]) });
  if (!sbOk(rows)) return { __error: true, message: "خطا در ثبت: " + (rows?.message || "نامشخص") };
  return fromRow(rows[0]);
}

export async function updateCorrectiveAction(id, rec) {
  const payload = toDb(rec);
  payload.updated_at = new Date().toISOString();
  const rows = await sb(`corrective_actions?id=eq.${id}`, { method: "PATCH", body: JSON.stringify(payload) });
  if (!sbOk(rows)) return { __error: true, message: "خطا در ذخیره‌سازی: " + (rows?.message || "نامشخص") };
  return fromRow(rows[0]);
}

export async function deleteCorrectiveAction(id) {
  const result = await sb(`corrective_actions?id=eq.${id}`, { method: "DELETE", prefer: "return=minimal" });
  if (!sbOk(result)) return { __error: true, message: "خطا در حذف" };
  return { ok: true };
}

// تأیید نهایی HSE/کارفرما — وضعیت را به «بسته‌شده» می‌برد
export async function approveCorrectiveAction(id, approvedBy, approverNotes) {
  return updateCorrectiveAction(id, {
    status: "closed",
    approvedBy,
    approvedAt: new Date().toISOString(),
    approverNotes: approverNotes || "",
  });
}

// ---------- اتصال به موتور اثربخشی BowTie (فاز ۴) ----------
// آیا همین الان یک اقدام اصلاحیِ «باز» (هر وضعیتی جز بسته‌شده) برای این
// Barrier وجود دارد؟ — پایه‌ی جلوگیری از تکرار در بازمحاسبه‌های بعدی.
export async function findOpenCorrectiveActionForBarrier(barrierId) {
  const companyId = getCurrentCompanyId();
  const filter = companyId ? `&company_id=eq.${companyId}` : "";
  const rows = await sb(`corrective_actions?linked_barrier_id=eq.${barrierId}&status=neq.closed${filter}&select=id&limit=1`);
  return sbOk(rows) && rows.length > 0 ? rows[0].id : null;
}

// اقدام اصلاحی خودکار برای یک Barrier که اثربخشی‌اش از حد مجاز پایین‌تر
// آمده — عمداً از همان createCorrectiveAction موجود استفاده می‌کند (همان
// شماره‌گذاری خودکار CA-xxxx، همان اسکوپ company_id) تا هیچ مسیر جدیدی
// در ساختار داده باز نشود؛ فقط چند فیلد اضافه (اتصال به بریر/بوتای،
// auto_generated) را با خودش حمل می‌کند.
export async function createAutoCorrectiveActionForBarrier({ barrierId, barrierLabel, bowtieId, bowtieTitle, score, companyId }) {
  const existingId = await findOpenCorrectiveActionForBarrier(barrierId);
  if (existingId) return { skipped: true, reason: "duplicate", existingId };

  const priority = score < 40 ? "critical" : "high";
  const rec = {
    source: "bowtie",
    nonconformanceDescription: `کاهش خودکار اثربخشی Barrier «${barrierLabel}» در BowTie «${bowtieTitle}» به ${score}٪ (کمتر از حد مجاز تعیین‌شده برای این کنترل)`,
    rootCause: "افزایش شواهد Anomaly مرتبط با این Barrier و/یا باز ماندن اقدامات اصلاحی پیشین مرتبط با همان شواهد",
    actionDescription: "بازبینی و تقویت این کنترل (Barrier) توسط HSE موردنیاز است.",
    priority,
    status: "open",
    linkedBarrierId: barrierId,
    linkedBowtieId: bowtieId,
    autoGenerated: true,
  };
  // اگر company_id واقعیِ BowTie در دسترس بود، صریحاً همان استفاده می‌شود
  // (نه company_id نشست فعلی) — ورودی سوم createCorrectiveAction برای
  // همین منظور اضافه شده؛ اگر ارسال نشود، به رفتار قبلی (نشست فعلی) برمی‌گردد.
  const created = await createCorrectiveAction(rec, "سیستم — تولید خودکار (افت اثربخشی Barrier)", companyId);
  if (created?.__error) return created;
  return { ok: true, created };
}

// ---------- آپلود پیوست (Storage) ----------

export async function uploadCorrectiveActionFile(base64Data, fileName, contentType) {
  const path = `${Date.now()}-${fileName.replace(/[^a-zA-Z0-9._-]/g, "_")}`;
  try {
    const url = await uploadBase64ToStorage("corrective-action-files", path, base64Data, contentType);
    return { name: fileName, url };
  } catch (e) {
    return { __error: true, message: e?.message || "خطا در آپلود فایل" };
  }
}

